-- Existencias por bodega y variante (producto + color + talla). Definición real
-- exportada de Supabase el 21/10/2026. id_talla e id_color repiten los de la
-- variante: la app los toma de producto_variantes al registrar existencias.
-- Cada cambio de cantidad queda en movimientos_inventario (trigger
-- trg_inventario_movimiento, en incremento4_inventario_variantes.sql).
create table if not exists public.inventario (
  id_inventario bigint generated by default as identity not null,
  id_bodega bigint not null,
  id_variante bigint not null,
  id_talla bigint not null,
  id_color bigint not null,
  cantidad integer default 0 not null,
  fecha_actualizacion timestamp with time zone default now() not null,
  usuario_actualizacion text default 'Admin'::text not null,
  cantidad_defectuosa integer default 0 not null,
  constraint inventario_cantidad_check check ((cantidad >= 0)),
  constraint inventario_cantidad_defectuosa_check check ((cantidad_defectuosa >= 0)),
  constraint inventario_id_bodega_fkey foreign key (id_bodega) references bodegas(id_bodega),
  constraint inventario_id_color_fkey foreign key (id_color) references colores(id_color),
  constraint inventario_id_talla_fkey foreign key (id_talla) references tallas(id_talla),
  constraint inventario_id_variante_fkey foreign key (id_variante) references producto_variantes(id_variante),
  constraint inventario_pkey primary key (id_inventario),
  constraint inventario_ubicacion_producto_unica unique (id_bodega, id_variante, id_talla, id_color)
);

-- Fecha de la última modificación de cada fila (trigger exportado el 21/10/2026).
create or replace function public.fn_inventario_fecha()
 returns trigger
 language plpgsql
 set search_path to 'public'
as $function$
begin
  new.fecha_actualizacion := now();
  return new;
end $function$;

drop trigger if exists trg_inventario_fecha on public.inventario;
create trigger trg_inventario_fecha before update on public.inventario
  for each row execute function fn_inventario_fecha();
