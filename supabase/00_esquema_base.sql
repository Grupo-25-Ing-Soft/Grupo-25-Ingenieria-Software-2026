create table if not exists public.cortes (
  id_corte bigint generated by default as identity not null,
  fecha_corte date,
  cantidad_producto integer not null,
  cantidad_material bigint,
  observaciones text,
  cortador text,
  material_usado text,
  producto_asociado bigint,
  estado text default 'pendiente'::text not null,
  fecha_ingreso timestamp with time zone,
  id_bodega_ingreso bigint,
  id_pedido bigint,
