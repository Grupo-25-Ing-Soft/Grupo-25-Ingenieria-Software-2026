-- Número de pedido PED-000001, PED-000002... si la app no envía uno.
create sequence if not exists public.pedidos_numero_seq;

create or replace function public.fn_pedidos_numero()
 returns trigger
 language plpgsql
as $function$
begin
  if new.numero_pedido is null then
    new.numero_pedido := 'PED-' || lpad(nextval('public.pedidos_numero_seq')::text, 6, '0');
  end if;
  return new;
end;
$function$;

drop trigger if exists tg_pedidos_numero on public.pedidos;
create trigger tg_pedidos_numero before insert on public.pedidos
  for each row execute function fn_pedidos_numero();

