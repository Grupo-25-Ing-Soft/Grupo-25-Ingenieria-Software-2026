-- =====================================================================
-- Esquema base: tablas que existían en Supabase sin un script de creación.
--
-- Exportado el 21/10/2026 desde el catálogo de la base (pg_attribute,
-- pg_constraint y pg_trigger). Usa "create table if not exists": sobre la base
-- actual no cambia nada; en una base nueva crea las tablas como están hoy.
--
-- Orden de ejecución de los scripts de supabase/ en una base nueva:
--   1. 00_esquema_base.sql            (este archivo)
--   2. inventario.sql
--   3. facturas.sql, notas_credito.sql, pagos.sql, parametros_sistema.sql, roles.sql
--   4. incremento3_despachos.sql      (despachos y vistas de informes)
--   5. incremento3_ean.sql            (códigos EAN y sus triggers)
--   6. incremento4_campos_documento0.sql
--   7. incremento4_feedback.sql
--   8. incremento4_despachos.sql      (reemplaza registrar_despacho, anular_despacho,
--                                      v_pendientes_despacho y v_inventario_analisis)
--   9. incremento4_inventario_variantes.sql
--  10. incremento4_limpieza.sql        (elimina las funciones buscar* sin uso; opcional)
--  11. incremento4_ingreso_produccion.sql (ingresar_guia_corte por color, talla y cantidad)
--  12. incremento4_feedback_productos.sql (EAN con productos.codigo y presets de tallas)
--  13. incremento4_cortes_cantidades.sql  (v_productos_en_proceso sin color ni talla base)
--  14. incremento4_feedback_documentos.sql (quita detalle_pedidos.precio_unitario y subtotal, las
--                                      copias del cliente en facturas y cambia los estados de pedidos)
-- Los scripts posteriores reemplazan funciones y vistas de los anteriores: no
-- volver a ejecutar uno antiguo sobre la base actual.
-- El paso 4 ya no crea v_pendientes_despacho ni v_inventario_analisis (las crea el
-- paso 8) y v_despachos_detalle toma el folio como numero_factura, así que la
-- secuencia corre en una base nueva. No se ha probado en un PostgreSQL vacío.
--
-- Notas:
--   * detalle_pedidos.subtotal es una columna generada: la calcula la base y no se
--     puede enviar desde la app.
--   * tallas.talla es numérica (bigint); lo que se imprime (S, M, L...) va en nombre.
--   * producto_variantes.stock es una columna antigua: el stock real está en inventario.
--   * Las restricciones de clientes (descuentos, lista de precios, vendedor), de
--     producto_variantes (precios, EAN) y de cortes (pedido) las agregan también los
--     scripts de incremento con "add column if not exists".
-- =====================================================================

create table if not exists public.bodegas (
  id_bodega bigint generated by default as identity not null,
  descripcion character varying,
  codigo text,
  constraint "Bodega_pkey" primary key (id_bodega)
);

create table if not exists public.colores (
  id_color bigint generated by default as identity not null,
  descripcion character varying,
  codigo_color text,
  codigo_ean text,
  constraint "Color_pkey" primary key (id_color),
  constraint colores_codigo_ean_check check ((codigo_ean ~ '^[0-9]+$'::text))
);

create table if not exists public.tallas (
  id_talla bigint generated by default as identity not null,
  talla bigint not null,
  nombre text,
  codigo_ean text,
  constraint talla_pkey primary key (id_talla),
  constraint tallas_codigo_ean_check check ((codigo_ean ~ '^[0-9]+$'::text))
);

create table if not exists public.zona_venta (
  id_zona_venta bigint generated by default as identity not null,
  descripcion character varying,
  codigo text,
  nombre text default ''::text not null,
  constraint "Zona de Venta_pkey" primary key (id_zona_venta)
);

create table if not exists public.vendedores (
  id_vendedor bigint generated by default as identity not null,
  rut text not null,
  nombre text not null,
  digito_verificador character varying not null,
  porcentaje_comision real,
  codigo text,
  constraint vendedores_pkey primary key (id_vendedor),
  constraint vendedores_rut_key unique (rut)
);

create table if not exists public.productos (
  id_producto bigint generated by default as identity not null,
  descripcion text not null,
  abreviacion text,
  color bigint,
  precio bigint,
  talla bigint,
  codigo text,
  codigo_ean text,
  constraint productos_codigo_ean_check check ((codigo_ean ~ '^[0-9]+$'::text)),
  constraint productos_color_fkey foreign key (color) references colores(id_color),
  constraint productos_pkey primary key (id_producto),
  constraint productos_talla_fkey foreign key (talla) references tallas(id_talla)
);

create table if not exists public.clientes (
  id_cliente bigint generated by default as identity not null,
  rut text not null,
  nombre text not null,
  correo text,
  telefono text,
  direccion text,
  digito_verificador character varying not null,
  abreviacion text,
  ciudad text,
  comuna text,
  condiciones_venta text,
  via_despacho text,
  porcentaje_comision real,
  porcentaje_cobranza real,
  observaciones text,
  id_zona_venta bigint,
  descuento_1 numeric(5,2) default 0 not null,
  descuento_2 numeric(5,2) default 0 not null,
  descuento_3 numeric(5,2) default 0 not null,
  codigo text,
  giro text,
  telefono_2 text,
  lista_precios smallint default 1 not null,
  id_vendedor bigint,
  constraint clientes_descuento_1_check check (((descuento_1 >= (0)::numeric) and (descuento_1 <= (100)::numeric))),
  constraint clientes_descuento_2_check check (((descuento_2 >= (0)::numeric) and (descuento_2 <= (100)::numeric))),
  constraint clientes_descuento_3_check check (((descuento_3 >= (0)::numeric) and (descuento_3 <= (100)::numeric))),
  constraint clientes_id_vendedor_fkey foreign key (id_vendedor) references vendedores(id_vendedor),
  constraint clientes_id_zona_venta_fkey foreign key (id_zona_venta) references zona_venta(id_zona_venta),
  constraint clientes_lista_precios_check check ((lista_precios >= 1)),
  constraint clientes_pkey primary key (id_cliente),
  constraint clientes_rut_key unique (rut)
);

create table if not exists public.producto_variantes (
  id_variante bigint generated by default as identity not null,
  id_producto bigint not null,
  id_color bigint,
  id_talla bigint,
  codigo_ean text,
  precio_venta integer default 0 not null,
  stock integer default 0 not null,
  activo boolean default true not null,
  creado_en timestamp with time zone default now() not null,
  descripcion text,
  ean_manual boolean default false not null,
  precio_costo integer default 0 not null,
  precio_detalle integer default 0 not null,
  precio_liquidacion integer default 0 not null,
  en_liquidacion boolean default false not null,
  constraint producto_variantes_codigo_ean_key unique (codigo_ean),
  constraint producto_variantes_color_fkey foreign key (id_color) references colores(id_color),
  constraint producto_variantes_pkey primary key (id_variante),
  constraint producto_variantes_precio_check check ((precio_venta >= 0)),
  constraint producto_variantes_precio_costo_check check ((precio_costo >= 0)),
  constraint producto_variantes_precio_detalle_check check ((precio_detalle >= 0)),
  constraint producto_variantes_precio_liquidacion_check check ((precio_liquidacion >= 0)),
  constraint producto_variantes_producto_fkey foreign key (id_producto) references productos(id_producto) on delete cascade,
  constraint producto_variantes_stock_check check ((stock >= 0)),
  constraint producto_variantes_talla_fkey foreign key (id_talla) references tallas(id_talla),
  constraint producto_variantes_unica unique (id_producto, id_color, id_talla)
);

create table if not exists public.pedidos (
  id_pedido bigint generated by default as identity not null,
  cliente_asociado bigint not null,
  fecha_pedido date default current_date not null,
  fecha_entrega date,
  vendedor_asociado bigint not null,
  numero_pedido text not null,
  estado text default 'pendiente'::text not null,
  motivo_anulacion text,
  fecha_anulacion timestamp with time zone,
  usuario_anulacion text,
  codigo text,
  constraint pedidos_cliente_asociado_fkey foreign key (cliente_asociado) references clientes(id_cliente),
  constraint pedidos_estado_check check ((estado = any (array['pendiente'::text, 'confirmado'::text, 'en_produccion'::text,
                                                               'despachado'::text, 'entregado'::text, 'anulado'::text]))),
  constraint pedidos_fechas_check check (((fecha_entrega is null) or (fecha_entrega >= fecha_pedido))),
  constraint pedidos_numero_pedido_uk unique (numero_pedido),
  constraint pedidos_pkey primary key (id_pedido),
  constraint pedidos_vendedor_asociado_fkey foreign key (vendedor_asociado) references vendedores(id_vendedor)
);

create table if not exists public.detalle_pedidos (
  id_detalle_pedido bigint generated always as identity not null,
  id_pedido bigint not null,
  id_variante bigint not null,
  cantidad integer not null,
  precio_unitario integer not null,
  subtotal integer generated always as ((cantidad * precio_unitario)) stored,
  observacion text,
  cantidad_anulada integer default 0 not null,
  constraint detalle_pedidos_cantidad_anulada_check check ((cantidad_anulada >= 0)),
  constraint detalle_pedidos_cantidad_check check ((cantidad > 0)),
  constraint detalle_pedidos_linea_uk unique (id_pedido, id_variante),
  constraint detalle_pedidos_pedido_fkey foreign key (id_pedido) references pedidos(id_pedido) on delete cascade,
  constraint detalle_pedidos_pkey primary key (id_detalle_pedido),
  constraint detalle_pedidos_precio_check check ((precio_unitario >= 0)),
  constraint detalle_pedidos_variante_fkey foreign key (id_variante) references producto_variantes(id_variante)
