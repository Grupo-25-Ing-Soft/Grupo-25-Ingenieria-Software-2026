-- Incremento 4: usuarios, roles y permisos configurables (RF-057/058).
-- No hay roles predefinidos: el administrador crea los que necesite y elige,
-- por cada módulo del sistema, si el rol puede verlo y/o editarlo.
-- El primer usuario se crea desde la pantalla de inicio de sesión y queda
-- como superusuario (acceso total), para poder crear los demás roles.
-- Ejecutar una vez en el SQL Editor de Supabase.

create table if not exists public.roles (
  id_rol bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text,
  creado_en timestamptz not null default now()
);

-- Un registro por módulo con permiso; si el módulo no aparece, el rol no tiene acceso.
-- Los códigos de módulo están definidos en MODULOS_SISTEMA (realFlask.py).
create table if not exists public.rol_permisos (
  id_rol bigint not null references public.roles (id_rol) on delete cascade,
  modulo text not null,
  puede_ver boolean not null default false,
  puede_editar boolean not null default false,
  primary key (id_rol, modulo)
);

create table if not exists public.usuarios (
  id_usuario bigint generated by default as identity primary key,
  nombre_usuario text not null unique,
  nombre text not null,
  password_hash text not null,
  id_rol bigint references public.roles (id_rol) on delete restrict,
  es_superusuario boolean not null default false,
  activo boolean not null default true,
  correo text,
  creado_en timestamptz not null default now()
);

-- En el proyecto ya existía una tabla "usuarios" vacía (id_usuario, nombre, correo,
-- activo, creado_en). Si es así, el create anterior no hace nada y aquí se le
-- agregan las columnas que faltan, sin borrar las que ya tiene.
alter table public.usuarios
  add column if not exists nombre_usuario text,
  add column if not exists nombre text,
  add column if not exists password_hash text,
  add column if not exists id_rol bigint references public.roles (id_rol) on delete restrict,
  add column if not exists es_superusuario boolean not null default false,
  add column if not exists activo boolean not null default true,
  add column if not exists correo text,
  add column if not exists creado_en timestamptz not null default now();
-- La tabla está vacía, así que se pueden exigir estos campos sin problema.
alter table public.usuarios alter column nombre_usuario set not null;
alter table public.usuarios alter column nombre set not null;
alter table public.usuarios alter column password_hash set not null;
-- El correo es opcional en el formulario de usuarios.
alter table public.usuarios alter column correo drop not null;
-- La tabla que ya existía traía otras columnas obligatorias que la app no usa
-- (por ejemplo tipo_usuario, reemplazado por los roles). Se dejan opcionales
-- para que se puedan crear usuarios; no se borra ninguna columna.
do $$
declare
  columna record;
begin
  for columna in
    select column_name
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'usuarios'
      and is_nullable = 'NO'
      and column_default is null
      and is_identity = 'NO'
      and column_name not in ('id_usuario', 'nombre_usuario', 'nombre', 'password_hash')
  loop
    execute format('alter table public.usuarios alter column %I drop not null', columna.column_name);
  end loop;
end $$;

create unique index if not exists usuarios_nombre_usuario_key on public.usuarios (nombre_usuario);
create index if not exists usuarios_id_rol_idx on public.usuarios (id_rol);

-- Mismas políticas abiertas que el resto de las tablas: la publishable key solo
-- vive en el servidor Flask (.env), que es quien aplica los permisos.
alter table public.roles enable row level security;
alter table public.rol_permisos enable row level security;
alter table public.usuarios enable row level security;

drop policy if exists "Enable all access for all users" on public.roles;
create policy "Enable all access for all users" on public.roles
  for all using (true) with check (true);
drop policy if exists "Enable all access for all users" on public.rol_permisos;
create policy "Enable all access for all users" on public.rol_permisos
  for all using (true) with check (true);
drop policy if exists "Enable all access for all users" on public.usuarios;
create policy "Enable all access for all users" on public.usuarios
  for all using (true) with check (true);

-- Comprobación: debe listar al menos las columnas id_usuario, nombre_usuario, nombre,
-- password_hash, id_rol, es_superusuario, activo y correo. Si aparece otra columna
-- con is_nullable = 'NO' y sin column_default, la app no podrá crear usuarios.
select column_name, data_type, is_nullable, column_default
from information_schema.columns
where table_schema = 'public' and table_name = 'usuarios'
order by ordinal_position;
